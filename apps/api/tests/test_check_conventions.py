"""Unit tests for scripts/check_conventions.py."""

import importlib.util
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[3]
SCRIPT = ROOT / "scripts/check_conventions.py"


def _load_checker():
    spec = importlib.util.spec_from_file_location("check_conventions", SCRIPT)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def _init_repo(tmp_path: Path) -> Path:
    subprocess.run(["git", "init", "-q", str(tmp_path)], check=True)
    return tmp_path


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def test_current_repository_passes_all_convention_checks():
    checker = _load_checker()
    assert checker.run_all_checks(ROOT) == []
    result = subprocess.run(
        ["python3", str(SCRIPT)],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    assert result.returncode == 0, result.stderr


def test_detects_random_uuid_and_network_calls_with_exemptions(tmp_path):
    checker = _load_checker()
    repo = _init_repo(tmp_path)
    # Allowed locations and comments must pass.
    _write(repo / "apps/web/src/lib/id.ts", "export const newId = () => crypto.randomUUID();\n")
    _write(repo / "apps/web/src/lib/id.test.ts", "crypto.randomUUID();\nfetch('/api/x');\n")
    _write(repo / "apps/web/src/api/client.ts", "export const get = () => fetch('/api/v1');\n")
    _write(
        repo / "apps/web/src/lib/agentConversation.ts",
        "export const read = () => fetch('/api/conversations/1/files/a.txt');\n",
    )
    _write(
        repo / "apps/web/src/pages/CleanPage.tsx",
        "// Avoid crypto.randomUUID and fetch() here.\nconst fetching = false;\n",
    )
    assert checker.check_random_uuid(repo) == []
    assert checker.check_network_calls(repo) == []

    # Direct calls outside allowed paths fail with exact file:line.
    _write(
        repo / "apps/web/src/pages/BadPage.tsx",
        "const a = 1;\nconst id = crypto.randomUUID();\nconst r = fetch('/api/bad');\nconst s = new EventSource('/events');\n",
    )
    uuid_errors = checker.check_random_uuid(repo)
    assert [(v.path, v.line) for v in uuid_errors] == [("apps/web/src/pages/BadPage.tsx", 2)]
    net_errors = checker.check_network_calls(repo)
    assert [(v.path, v.line) for v in net_errors] == [
        ("apps/web/src/pages/BadPage.tsx", 3),
        ("apps/web/src/pages/BadPage.tsx", 4),
    ]


def test_detects_extra_css_forbidden_tracked_paths_and_table_format_drift(tmp_path):
    checker = _load_checker()
    repo = _init_repo(tmp_path)
    _write(repo / "apps/web/src/styles/tokens.css", ":root {}\n")
    _write(repo / "apps/web/src/styles/index.css", "@import './tokens.css';\n")
    _write(repo / "apps/web/src/pages/extra.css", ".box {}\n")
    assert [(v.path, v.line) for v in checker.check_css_files(repo)] == [
        ("apps/web/src/pages/extra.css", 1)
    ]

    # .claude-plugin is allowed; .claude/ and other forbidden dirs are not.
    _write(repo / ".claude-plugin/marketplace.json", "{}\n")
    _write(repo / ".claude/settings.local.json", "{}\n")
    _write(repo / "docs/design/prototypes/mock.html", "<div/>\n")
    _write(repo / "integrations/dataagent/dist/bundle.zip", "zip\n")
    subprocess.run(
        [
            "git",
            "-C",
            str(repo),
            "add",
            "-f",
            ".claude-plugin/marketplace.json",
            ".claude/settings.local.json",
            "docs/design/prototypes/mock.html",
            "integrations/dataagent/dist/bundle.zip",
        ],
        check=True,
    )
    tracked_errors = checker.check_tracked_forbidden_paths(repo)
    assert [v.path for v in tracked_errors] == [
        ".claude/settings.local.json",
        "docs/design/prototypes/mock.html",
        "integrations/dataagent/dist/bundle.zip",
    ]

    # table_format.py drift check.
    _write(
        repo / "apps/api/src/ontofoundry_api/domain/table_reading.py",
        "def clean(v):\n    return v\n",
    )
    _write(
        repo / "integrations/dataagent/shared/scripts/table_format.py",
        "# Generated by generate_output_schemas.py; do not edit.\ndef clean(v):\n    return None\n",
    )
    sync_errors = checker.check_generated_artifacts_sync(repo)
    assert [(v.path, v.line) for v in sync_errors] == [
        ("integrations/dataagent/shared/scripts/table_format.py", 1)
    ]

    # CLI exits 1 and prints file:line in stderr.
    cli = subprocess.run(
        ["python3", str(SCRIPT), "--root", str(repo)],
        capture_output=True,
        text=True,
        check=False,
    )
    assert cli.returncode == 1
    assert "apps/web/src/pages/extra.css:1:" in cli.stderr
    assert ".claude/settings.local.json:1:" in cli.stderr
    assert "AGENTS.md" in cli.stderr
