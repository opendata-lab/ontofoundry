#!/usr/bin/env python3
"""Mechanically enforce AGENTS.md repository conventions in CI (stdlib only)."""

from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]

WEB_SRC = Path("apps/web/src")
SCRIPT_EXTENSIONS = {".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs"}
STYLE_EXTENSIONS = {".css", ".scss", ".sass", ".less"}

ALLOWED_RANDOM_UUID_FILES = {
    "apps/web/src/lib/id.ts",
}

# Only api/client.ts performs HTTP calls under apps/web/src/api/ today
# (definitionReads.ts is an in-memory cache; types.ts and core.generated.ts are types).
ALLOWED_NETWORK_CALL_FILES = {
    "apps/web/src/api/client.ts",
}

# Existing exceptions outside api/client.ts, each requiring an explicit reason.
NETWORK_CALL_ALLOWLIST: dict[str, str] = {
    "apps/web/src/lib/agentConversation.ts": (
        "Adapts @opendataagent/agent-conversation HTTP transport with "
        "authenticated blob reads (readFile) for conversation attachments."
    ),
}

ALLOWED_CSS_FILES = {
    "apps/web/src/styles/tokens.css",
    "apps/web/src/styles/index.css",
}

FORBIDDEN_TRACKED_PREFIXES = (
    ".claude",
    "docs/design/prototypes",
    "integrations/dataagent/dist",
)

TABLE_FORMAT_SOURCE = Path("apps/api/src/ontofoundry_api/domain/table_reading.py")
TABLE_FORMAT_TARGET = Path("integrations/dataagent/shared/scripts/table_format.py")
TABLE_FORMAT_HEADER = "# Generated by generate_output_schemas.py; do not edit.\n"

RANDOM_UUID_RE = re.compile(r"\bcrypto\.randomUUID\b")
NETWORK_CALL_RE = re.compile(
    r"(?:(?<![.\w$])|\b(?:window|globalThis|self)\.)fetch\s*\("
    r"|\baxios\b"
    r"|\bnew\s+(?:EventSource|WebSocket|XMLHttpRequest)\b"
)

# Match JS/TS string literals (keep as-is) or comments (replace with spaces/newlines).
JS_TOKEN_RE = re.compile(
    r'"(?:\\.|[^"\\])*"'
    r"|'(?:\\.|[^'\\])*'"
    r"|`(?:\\.|[^`\\])*`"
    r"|//[^\n]*"
    r"|/\*[\s\S]*?\*/"
)

RULE_RANDOM_UUID = (
    "AGENTS.md 代码约定：生成 id 统一用 lib/id.ts 的 newId()，"
    "不要直接调用 crypto.randomUUID（局域网 HTTP 非安全上下文不可用）。"
)
RULE_NETWORK_CALL = (
    "AGENTS.md 代码约定：前端接口调用统一走 api/client.ts，"
    "不要在其他源码中直接发起网络请求（fetch/axios/EventSource/WebSocket）。"
)
RULE_CSS_FILES = (
    "AGENTS.md 代码约定：apps/web/src 只保留 styles/tokens.css 和 "
    "styles/index.css，不新增零散 CSS 文件。"
)
RULE_FORBIDDEN_TRACKED = (
    "AGENTS.md 协作约定：不提交 .claude/、docs/design/prototypes/、"
    "integrations/dataagent/dist/ 下的文件。"
)
RULE_TABLE_FORMAT_SYNC = (
    "AGENTS.md 代码约定：integrations/dataagent/shared/scripts/table_format.py "
    "与源模块 apps/api/src/ontofoundry_api/domain/table_reading.py 不一致，"
    "请运行 make -C integrations/dataagent schemas 重新生成。"
)


@dataclass(frozen=True)
class Violation:
    path: str
    line: int
    rule: str

    def format(self) -> str:
        return f"{self.path}:{self.line}: {self.rule}"


def _is_web_test(rel_path: str) -> bool:
    name = Path(rel_path).name
    parts = Path(rel_path).parts
    return (
        "__tests__" in parts
        or ".test." in name
        or ".spec." in name
    )


def _strip_js_comments(source: str) -> str:
    """Remove // and /* */ comments while preserving string literals and line numbers."""

    def replace(match: re.Match[str]) -> str:
        text = match.group(0)
        if text.startswith("//"):
            return ""
        if text.startswith("/*"):
            return "\n" * text.count("\n")
        return text

    return JS_TOKEN_RE.sub(replace, source)


def _iter_web_files(root: Path, extensions: set[str]) -> list[tuple[str, Path]]:
    base = root / WEB_SRC
    if not base.is_dir():
        return []
    found: list[tuple[str, Path]] = []
    for path in sorted(base.rglob("*")):
        if path.is_file() and path.suffix in extensions:
            found.append((path.relative_to(root).as_posix(), path))
    return found


def check_random_uuid(root: Path) -> list[Violation]:
    violations: list[Violation] = []
    for rel_path, path in _iter_web_files(root, SCRIPT_EXTENSIONS):
        if rel_path in ALLOWED_RANDOM_UUID_FILES or _is_web_test(rel_path):
            continue
        cleaned = _strip_js_comments(path.read_text(encoding="utf-8"))
        for lineno, line in enumerate(cleaned.splitlines(), start=1):
            if RANDOM_UUID_RE.search(line):
                violations.append(Violation(rel_path, lineno, RULE_RANDOM_UUID))
    return violations


def check_network_calls(root: Path) -> list[Violation]:
    allowed = ALLOWED_NETWORK_CALL_FILES | set(NETWORK_CALL_ALLOWLIST)
    violations: list[Violation] = []
    for rel_path, path in _iter_web_files(root, SCRIPT_EXTENSIONS):
        if rel_path in allowed or _is_web_test(rel_path):
            continue
        cleaned = _strip_js_comments(path.read_text(encoding="utf-8"))
        for lineno, line in enumerate(cleaned.splitlines(), start=1):
            if NETWORK_CALL_RE.search(line):
                violations.append(Violation(rel_path, lineno, RULE_NETWORK_CALL))
    return violations


def check_css_files(root: Path) -> list[Violation]:
    violations: list[Violation] = []
    for rel_path, _ in _iter_web_files(root, STYLE_EXTENSIONS):
        if rel_path not in ALLOWED_CSS_FILES:
            violations.append(Violation(rel_path, 1, RULE_CSS_FILES))
    return violations


def check_tracked_forbidden_paths(root: Path) -> list[Violation]:
    result = subprocess.run(
        ["git", "-C", str(root), "ls-files", "-z", "--", *FORBIDDEN_TRACKED_PREFIXES],
        capture_output=True,
        check=True,
    )
    entries = [
        item.decode("utf-8", errors="replace")
        for item in result.stdout.split(b"\0")
        if item
    ]
    return [Violation(path, 1, RULE_FORBIDDEN_TRACKED) for path in sorted(entries)]


def check_generated_artifacts_sync(root: Path) -> list[Violation]:
    """Verify generated artifacts not already checked by pytest or Node CI steps.

    Note:
    - apps/api/src/ontofoundry_api/contracts/*.schema.json are checked by
      apps/api/tests/test_read_contracts.py (export_schema.export(check=True)),
      test_core1_schema.py and test_t1_proposal_contract.py.
    - integrations/dataagent/skills/*/output-schema.json are checked by
      integrations/dataagent/tests/test_packages.py.
    - apps/web/src/api/core.generated.ts is checked in the Node CI job via
      `npm run check:core-types -w ontofoundry-web` (generate_core_types.mjs --check).
    - integrations/dataagent/shared/scripts/table_format.py is overwritten in place
      when test_packages.py calls generate(), so drift must be checked here first.
    """
    source = root / TABLE_FORMAT_SOURCE
    target = root / TABLE_FORMAT_TARGET
    if not source.is_file() or not target.is_file():
        return []
    expected = TABLE_FORMAT_HEADER + source.read_text(encoding="utf-8")
    actual = target.read_text(encoding="utf-8")
    if actual != expected:
        return [Violation(TABLE_FORMAT_TARGET.as_posix(), 1, RULE_TABLE_FORMAT_SYNC)]
    return []


def run_all_checks(root: Path = ROOT) -> list[Violation]:
    violations: list[Violation] = []
    violations.extend(check_random_uuid(root))
    violations.extend(check_network_calls(root))
    violations.extend(check_css_files(root))
    violations.extend(check_tracked_forbidden_paths(root))
    violations.extend(check_generated_artifacts_sync(root))
    return violations


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Check AGENTS.md conventions.")
    parser.add_argument(
        "--root",
        type=Path,
        default=ROOT,
        help="Repository root to inspect (defaults to this repository).",
    )
    args = parser.parse_args(argv)
    violations = run_all_checks(args.root.resolve())
    if violations:
        for item in violations:
            print(item.format(), file=sys.stderr)
        return 1
    print("AGENTS.md convention checks passed.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
